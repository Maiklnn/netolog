// Узел «Сборка демо-публикации».
// Готовит расписание выхода материалов в демо-среду: по одной записи на каждую версию
// публикации, со статусом не выше «на проверке». Плюс собирает текст раздела 5 шаблона.

const d = $json;

const TIMES = { 'Telegram': '09:00', 'ВКонтакте': '18:30' };
const CHECKER = 'контент-редактор (человек)';

// материалы, для которых агент написал полный текст — они готовы к проверке
const written = {};
(d.selected || []).forEach(function (s) { written[s.day] = s.kind; });

const rows = [];
(d.plan || []).forEach(function (p) {
  const kind = written[p.day];
  const status = kind === 'post' ? 'на проверке' : (kind === 'reels' ? 'на проверке' : 'черновик');
  const ready = kind ? 'готов' : 'нужен текст';
  (p.platforms && p.platforms.length ? p.platforms : ['Telegram', 'ВКонтакте']).forEach(function (platform) {
    rows.push({
      date: p.date,
      time: TIMES[platform] || '12:00',
      weekday: p.weekday,
      rubric: p.rubric,
      task: p.task,
      topic: p.topic,
      format: p.format,
      platform: platform,
      status: status,
      material: ready,
      checker: CHECKER,
    });
  });
});

