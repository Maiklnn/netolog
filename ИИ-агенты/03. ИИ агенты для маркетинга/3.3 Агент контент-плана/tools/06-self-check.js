// Узел «Самопроверка качества».
// Сводит все проверки предыдущих шагов в чек-лист из шести вопросов шаблона ДЗ,
// выставляет по каждому ответ «да / частично / нет» и пишет комментарий.

const d = $json;

const all = d.checks || [];

function group(names) {
  const hit = all.filter(function (c) {
    return names.some(function (n) { return c.name.indexOf(n) >= 0; });
  });
  const failed = hit.filter(function (c) { return !c.ok; });
  return {
    total: hit.length,
    passed: hit.length - failed.length,
    failed: failed.map(function (c) { return c.name; }),
    ok: hit.length > 0 && failed.length === 0,
  };
}

const gStrategy = group(['В плане 7 публикаций', 'Даты совпадают', 'Задачи распределены', 'Продающая публикация']);
const gAudience = group(['Нет посторонних рубрик', 'Использованы все четыре рубрики', 'Темы не повторяют']);
const gVariety = group(['Форматы только из', 'Один формат не идёт', 'Для проработки выбраны', 'Выбранные темы есть']);
const gTone = group(['Нет запрещённых формулировок', 'В рилсе нет запрещённых', 'Версии для Telegram', 'В Telegram нет хэштегов', 'ВКонтакте: не больше 3']);

function answer(g, okText, partialText) {
  if (g.ok) return { answer: 'да', comment: okText };
  if (g.passed > 0) {
    return { answer: 'частично', comment: partialText + ' Не прошли проверки: ' + g.failed.join('; ') + '.' };
  }
  return { answer: 'нет', comment: 'Ни одна проверка блока не пройдена: ' + g.failed.join('; ') + '.' };
}

