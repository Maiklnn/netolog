// --- раздел 1: переносим бриф в структуру шаблона ---------------------------
function briefSection(title) {
  const re = new RegExp('## \\d+\\. ' + title + '\\n([\\s\\S]*?)(?=\\n## \\d+\\. |$)');
  const m = brief.match(re);
  return m ? m[1].trim() : '';
}

// строки раздела без пустых
function sectionLines(title) {
  return briefSection(title).split(/\n/).map(function (l) { return l.trim(); })
    .filter(function (l) { return l.length > 0; });
}
// пункты списка, очищенные от хвостовых «;» и «.»
function listItems(lines) {
  return lines.filter(function (l) { return l.indexOf('- ') === 0; })
    .map(function (l) { return l.slice(2).replace(/[;.]\s*$/, '').trim(); });
}
// первый осмысленный абзац: не пункт списка и не строка-подзаголовок
function leadText(lines) {
  return lines.filter(function (l) {
    return l.indexOf('- ') !== 0 && l.slice(-1) !== ':';
  }).join(' ').trim();
}

