-- ---------------------------------------------------------------------------
-- ЗАДАНИЕ №1. Фильмы со специальным атрибутом "Behind the Scenes"
-- Три запроса — три разных способа работы с массивом special_features.
-- (Все три возвращают одни и те же 50 фильмов, но разными механизмами.)
-- ---------------------------------------------------------------------------

-- Способ 1: оператор сравнения с ANY (значение = любой элемент массива)
SELECT title            AS "Название фильма",
       special_features AS "Специальные атрибуты"
FROM film
WHERE 'Behind the Scenes' = ANY (special_features)
ORDER BY title;

-- Способ 2: оператор "содержит" @> (массив слева содержит указанный массив)
SELECT title            AS "Название фильма",
       special_features AS "Специальные атрибуты"
FROM film
WHERE special_features @> ARRAY['Behind the Scenes']
ORDER BY title;

-- Способ 3: оператор пересечения && (массивы имеют хотя бы один общий элемент)
SELECT title            AS "Название фильма",
       special_features AS "Специальные атрибуты"
FROM film
WHERE special_features && ARRAY['Behind the Scenes']
ORDER BY title;


-- ---------------------------------------------------------------------------
-- ЗАДАНИЕ №2. Платежи за 17-19 июня 2005 включительно, стоимость > 1.00
-- ---------------------------------------------------------------------------
SELECT payment_id   AS "Идентификатор платежа",
       amount       AS "Размер платежа",
       payment_date AS "Дата платежа"
FROM payment
WHERE payment_date::date BETWEEN '2005-06-17' AND '2005-06-19'
  AND amount > 1.00
ORDER BY payment_date;


-- ---------------------------------------------------------------------------
-- ЗАДАНИЕ №3. ТОП-5 покупателей по сумме платежей
-- Второй ключ сортировки (customer_id) нужен обязательно: у покупателей
-- 137 и 178 одинаковая сумма 194.61, без второго ключа порядок неустойчив.
-- ---------------------------------------------------------------------------
SELECT customer_id AS "Идентификатор пользователя",
       sum(amount) AS "Сумма платежей"
FROM payment
GROUP BY customer_id
ORDER BY sum(amount) DESC, customer_id
LIMIT 5;


-- ---------------------------------------------------------------------------
-- ЗАДАНИЕ №4. Количество предпочитаемых жанров у каждого покупателя
-- favorite_genres лежит в jsonb-поле preferences по пути profile.favorite_genres
-- ---------------------------------------------------------------------------
SELECT customer_id AS "Идентификатор пользователя",
       jsonb_array_length(preferences -> 'profile' -> 'favorite_genres')
           AS "Количество предпочитаемых жанров"
FROM customer
ORDER BY customer_id;


-- ---------------------------------------------------------------------------
-- ЗАДАНИЕ №5. Количество пользователей с отключённым email-уведомлением
-- ---------------------------------------------------------------------------
SELECT count(*) AS "Количество пользователей"
FROM customer
WHERE preferences @> '{"notifications": {"email": false}}'::jsonb;


-- ---------------------------------------------------------------------------
-- ЗАДАНИЕ №6. Сколько заплатил каждый покупатель за каждый месяц
-- date_trunc('month', ...) обрезает дату до первого числа месяца, поэтому
-- месяцы разных лет (2005 и 2006) не смешиваются.
-- ---------------------------------------------------------------------------
SELECT customer_id                      AS "Идентификатор пользователя",
       date_trunc('month', payment_date) AS "Месяц",
       sum(amount)                      AS "Сумма платежей"
FROM payment
GROUP BY customer_id, date_trunc('month', payment_date)
ORDER BY customer_id, date_trunc('month', payment_date);


-- ---------------------------------------------------------------------------
-- ЗАДАНИЕ №7. На какую сумму продал каждый сотрудник магазина
-- ---------------------------------------------------------------------------
SELECT staff_id    AS "Идентификатор сотрудника",
       sum(amount) AS "Сумма платежей"
FROM payment
GROUP BY staff_id
ORDER BY staff_id;


-- ---------------------------------------------------------------------------
-- ЗАДАНИЕ №8. Среднее количество дней возврата фильма по каждому покупателю,
-- округлённое до сотых.
-- Разницу считаем в секундах через date_part('epoch', ...), переводим в дни
-- и только потом усредняем — иначе дробная часть дней потерялась бы.
-- Платежи/аренды без даты возврата (NULL) функция avg() игнорирует.
-- ---------------------------------------------------------------------------
SELECT customer_id AS "Идентификатор пользователя",
       round(
           (avg(date_part('epoch', return_date - rental_date) / 86400))::numeric,
           2
       ) AS "Среднее количество дней"
FROM rental
GROUP BY customer_id
ORDER BY customer_id;


