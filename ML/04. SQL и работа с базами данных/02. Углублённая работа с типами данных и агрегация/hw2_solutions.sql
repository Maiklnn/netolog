-- ---------------------------------------------------------------------------
-- ДОП. №1. День недели, в который чаще всего берут фильмы (топ-1).
-- Подзапросы/СТЕ и приведение даты к строке не используются.
-- date_part('isodow', ...) даёт 1 = понедельник ... 7 = воскресенье.
-- FETCH FIRST 1 ROW WITH TIES выведет ВСЕ дни, если они делят первое место.
-- (Проверено: в этой базе максимум единственный — вторник, 2463 аренды,
--  поэтому тот же результат дал бы обычный LIMIT 1.)
-- ---------------------------------------------------------------------------
SELECT date_part('isodow', rental_date) AS "День недели",
       count(*)                         AS "Количество аренд"
FROM rental
GROUP BY date_part('isodow', rental_date)
ORDER BY count(*) DESC
FETCH FIRST 1 ROW WITH TIES;

