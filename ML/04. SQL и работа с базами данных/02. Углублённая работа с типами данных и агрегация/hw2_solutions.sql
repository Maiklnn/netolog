-- ---------------------------------------------------------------------------
-- ДОП. №2. Количество продаж у продавцов, которые принимали платежи,
-- плюс вычисляемая колонка "Премия" (порог 7300).
-- "Продажа" в базе проката — это оформленная аренда (rental), а "продавец" —
-- сотрудник staff, её оформивший. Условие "принимали платежи" реализовано
-- через IN: остаются только те staff_id, что встречаются в payment.
-- Подзапрос с DISTINCT нужен, чтобы соединение с payment не размножило строки.
-- ---------------------------------------------------------------------------
SELECT r.staff_id AS "Идентификатор сотрудника",
       count(*)   AS "Количество продаж",
       CASE
           WHEN count(*) > 7300 THEN 'Да'
           ELSE 'Нет'
       END        AS "Премия"
FROM rental r
WHERE r.staff_id IN (SELECT DISTINCT staff_id FROM payment)
GROUP BY r.staff_id
ORDER BY r.staff_id;


-- ---------------------------------------------------------------------------
-- ДОП. №3. ТОП-3 покупателя, арендовавших фильмы более 3 раз
-- в период с 10.06.2005 включительно по 13.06.2005 не включительно,
-- т.е. в полуинтервале [2005-06-10; 2005-06-13).
-- ---------------------------------------------------------------------------
SELECT customer_id AS "Идентификатор пользователя",
       count(*)    AS "Количество аренд"
FROM rental
WHERE rental_date >= '2005-06-10'
  AND rental_date <  '2005-06-13'
GROUP BY customer_id
HAVING count(*) > 3
ORDER BY count(*) DESC, customer_id
LIMIT 3;
